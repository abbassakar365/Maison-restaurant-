#!/usr/bin/env node
/* Regenerates the menu SQL from js/menu-data.js:
     sql/menu_seed.sql  – the first menu for an empty database
     sql/menu_sync.sql  – brings an already-seeded menu up to date (photos, labels, descriptions), matched by dish name
   Run from the repository root:  node scripts/menu-sql.mjs */
import { writeFileSync } from 'node:fs';
import { MENU } from '../js/menu-data.js';

const q = (text) => "'" + String(text).replace(/'/g, "''") + "'";
const photoPath = (slug) => (slug ? `images/menu/${slug}.webp` : null);
const sql = (value) => (value == null ? 'null' : q(value));

let seed = `-- First menu, copied from js/menu-data.js (only if the menu tables are empty).
-- Generated by scripts/menu-sql.mjs: edit js/menu-data.js and re-run it instead of editing this file.
-- photo_url points at the photos in images/menu/, served from the website itself.
do $$ begin
if exists (select 1 from public.menu_categories) then return; end if;
`;
const rows = [];
MENU.forEach((cat, c) => {
  seed += `insert into public.menu_categories (id, name, note, tint, sort) values (${q(cat.id)}, ${q(cat.name)}, ${q(cat.note || '')}, ${q(cat.tint || '')}, ${c + 1});\n`;
  seed += 'insert into public.menu_items (category_id, name, price, picture, photo_url, ingredients, description, tags, sort) values\n';
  seed += cat.items.map(([name, price, slug, ingredients, tags, description], i) =>
    `  (${q(cat.id)}, ${q(name)}, ${price}, '🍽️', ${sql(photoPath(slug))}, ${q(ingredients)}, ${q(description || '')}, ${q(tags || '')}, ${i + 1})`).join(',\n') + ';\n';
  cat.items.forEach(([name, , slug, , tags, description]) => rows.push(`  (${q(name)}, ${sql(photoPath(slug))}, ${q(tags || '')}, ${q(description || '')})`));
});
seed += 'end $$;\n';
writeFileSync('sql/menu_seed.sql', seed);

const sync = `-- Brings a menu that was seeded earlier in line with js/menu-data.js, matched by dish name (case-insensitive):
--   photo_url   filled in when the dish has no photo yet (uploaded photos are kept)
--   tags        replaced by the built-in labels (meat, poultry, fish & seafood and gluten were added after the first seed)
--   description filled in when the dish has none yet (descriptions the team wrote are kept)
-- Dishes the team added themselves are not touched. Run it once after updating the site; run sql/schema.sql first.
-- Generated by scripts/menu-sql.mjs.
update public.menu_items as m set
  photo_url = coalesce(m.photo_url, v.photo),
  tags = v.tags,
  description = case when m.description = '' then v.description else m.description end
from (values
${rows.join(',\n')}
) as v(name, photo, tags, description)
where lower(m.name) = lower(v.name);
`;
writeFileSync('sql/menu_sync.sql', sync);
console.log(`menu_seed.sql and menu_sync.sql written: ${MENU.length} categories, ${rows.length} dishes`);
